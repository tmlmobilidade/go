#!/bin/bash

# Generate the TypeScript rule IDs and Zod schema from validator rule filenames.
# Usage: ./generate-validator-rules.sh [--check] [output_directory]
#
# With --check, the output file is not changed. Package and Docker builds use
# the committed file.

set -eo pipefail

CHECK_ONLY=false
if [ "$1" = "--check" ]; then
    CHECK_ONLY=true
    shift
fi

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"
RULES_DIR="${PROJECT_ROOT}/packages-golang/gtfs-validator/src/rules"
OUTPUT_DIR="${1:-${PROJECT_ROOT}/packages-new/types/gtfs-validator/src/rules}"
TARGET="${OUTPUT_DIR}/rule-ids.ts"

TEMP_DIR=$(mktemp -d)
trap 'rm -rf "${TEMP_DIR}"' EXIT

if [ "${CHECK_ONLY}" = false ]; then
    printf 'Generating validator rule IDs from the Go validator...\n'
fi

RULE_IDS=$(find "${RULES_DIR}"/*-validations -type f -name '*.go' ! -name 'checks.go' ! -name '*_test.go' \
    | sed 's|.*/||; s/\.go$//' \
    | LC_ALL=C sort -u)

if [ -z "${RULE_IDS}" ]; then
    printf 'No validator rule files found in %s. Nothing was written.\n' "${RULES_DIR}" >&2
    exit 1
fi

SOURCE="${TEMP_DIR}/rule-ids.ts"
{
    cat <<'EOF'
/* * */

import { z } from 'zod';

/* * */

/**
 * This file is generated from rule filenames in packages-golang/gtfs-validator/src/rules.
 * Do not edit this file manually. Run `npm run repo:validator-rules` to regenerate.
 */

export const GtfsValidatorRuleIdValues = [
EOF

    while IFS= read -r rule_id; do
        printf "\t'%s',\n" "${rule_id}"
    done <<< "${RULE_IDS}"

    cat <<'EOF'
] as const;

export const GtfsValidatorRuleIdSchema = z
	.string()
	.transform(value => String(value).toLowerCase())
	.pipe(z.enum(GtfsValidatorRuleIdValues));

export type GtfsValidatorRuleId = z.infer<typeof GtfsValidatorRuleIdSchema>;
EOF
} > "${SOURCE}"

if [ "${CHECK_ONLY}" = true ]; then
    STALE=false
    if [ ! -f "${TARGET}" ]; then
        printf 'Missing validator rule IDs file: %s\n' "${TARGET}" >&2
        STALE=true
    elif ! diff -u "${TARGET}" "${SOURCE}"; then
        STALE=true
    fi
    if [ "${STALE}" = true ]; then
        printf 'Validator rule IDs are out of date. Run `npm run repo:validator-rules` and commit the result.\n' >&2
        exit 1
    fi
    printf 'Validator rule IDs are up to date.\n'
    exit 0
fi

mkdir -p "${OUTPUT_DIR}"
cp "${SOURCE}" "${TARGET}"
printf 'Wrote %s\n' "${TARGET}"
